interface IconHandle { startAnimation: () => void; stopAnimation: () => void }
type IconProps = Omit<SVGProps<SVGSVGElement>, 'ref'> & { size?: number | string };
function animated(Raw: ComponentType<any>, name: string) {
  return function AnimatedIcon({ size, className = '', strokeWidth = 1.8, style, ...props }: IconProps) {
    const host = useRef<HTMLSpanElement>(null);
    const controls = useRef<IconHandle>(null);
    const enabled = useSettingsStore(state => state.settings.animationsEnabled !== false);
    useEffect(() => {
      if (!enabled) return;
      const icon = host.current;
      const inNavigation = icon?.closest('.workspace-nav, .settings-index');
      const settingsIcon = icon?.closest('.settings-page') && ['palette', 'rocket', 'eye-dashed', 'circle', 'droplets', 'sparkles', 'sliders-horizontal', 'database', 'folder-lock', 'panel-bottom-close', 'folder-open', 'download'].includes(name);
      if (!inNavigation && !settingsIcon) return;
      const target = icon?.closest('button, a, [role="button"]') ?? icon;
      const start = () => controls.current?.startAnimation();
      const stop = () => controls.current?.stopAnimation();
      target?.addEventListener('mouseenter', start);
      target?.addEventListener('mouseleave', stop);
      target?.addEventListener('focusin', start);
      target?.addEventListener('focusout', stop);
      return () => {
        target?.removeEventListener('mouseenter', start);
        target?.removeEventListener('mouseleave', stop);
        target?.removeEventListener('focusin', start);
        target?.removeEventListener('focusout', stop);
      };
    }, [enabled]);
    return <span ref={host} {...props as any} aria-hidden="true" data-animated-icon={name}
      className={`animated-icon ${className}`} style={{ width: size, height: size, '--icon-stroke': strokeWidth, ...style } as CSSProperties}>
      {/* Remount at the resting pose when disabled: stopAnimation() itself
          animates back in upstream icons and can leave a visible transition. */}
      <Raw key={enabled ? 'animated' : 'static'} ref={controls} size={typeof size === 'number' ? size : 24} />
    </span>;
  };
}
